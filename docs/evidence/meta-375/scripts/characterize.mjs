// characterize.mjs — per-basis relationship characterization (META-375 Phase 3).
//
// Reads a dump from dump.mjs and adds, per qualifying relationship: endpoint
// existence at basis, endpoint roles, current-tree mechanical exposure classes,
// and held-out overlap over (basis, pin]. All rules frozen in
// PREREGISTRATION.md; classification regexes carried verbatim from META-374's
// frozen protocol/screen.mjs and protocol/exposure.mjs.
//
// Usage: node characterize.mjs <label> <dumpPath> <cloneDir> <pin> <basesJsonPath> <outDir>
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, extname, join } from 'node:path';

const [label, dumpPath, cloneDir, pin, basesJsonPath, outDir] = process.argv.slice(2);
const dump = JSON.parse(readFileSync(dumpPath, 'utf8'));
const bases = JSON.parse(readFileSync(basesJsonPath, 'utf8'));
const repoName = label.split('-')[0];
const repoCfg = bases.repos[repoName];
const basis = repoCfg.bases[label];
if (!basis) throw new Error(`no frozen basis for ${label}`);

const git = (...a) =>
  execFileSync('git', ['-C', cloneDir, '-c', 'diff.renamelimit=5000', ...a], {
    encoding: 'utf8',
    maxBuffer: 1 << 28,
  });

// ---- endpoint existence at basis (PREREGISTRATION §8) ----
const treeFiles = new Set(git('ls-tree', '-r', '--name-only', basis).split('\n'));
const contentCache = new Map();
const contentAtBasis = (p) => {
  if (contentCache.has(p)) return contentCache.get(p);
  let v = null;
  try {
    v = git('show', `${basis}:${p}`);
  } catch {
    v = null;
  }
  contentCache.set(p, v);
  return v;
};

// ---- endpoint roles (§9): single-label, exact precedence ----
const MANIFEST_LOCK_BASENAMES = new Set([
  'package.json', 'package-lock.json', 'pnpm-lock.yaml', 'yarn.lock',
  'Cargo.toml', 'Cargo.lock', 'MODULE.bazel', 'MODULE.bazel.lock',
  'WORKSPACE', 'WORKSPACE.bazel', 'Gemfile', 'Gemfile.lock',
  'composer.json', 'composer.lock', 'go.mod', 'go.sum',
  'deps.edn', 'project.clj', 'bb.edn', 'shadow-cljs.edn',
  '.release-please-manifest.json',
]);
const SOURCE_EXTS = new Set([
  '.rs', '.ts', '.tsx', '.js', '.jsx', '.mjs', '.cjs', '.clj', '.cljs', '.cljc',
  '.java', '.py', '.go', '.rb', '.c', '.h', '.cc', '.cpp', '.hpp', '.cs',
  '.kt', '.kts', '.swift', '.scala', '.vue', '.svelte', '.ex', '.exs', '.erl', '.hrl',
]);
const genMarker = (text) =>
  text !== null &&
  /generated|do not (edit|update|modify)|autogenerated/i.test(
    text.split('\n').slice(0, 10).join('\n'),
  );

function roleOf(p) {
  const base = basename(p);
  const ext = extname(p);
  const segs = p.split('/');
  if (MANIFEST_LOCK_BASENAMES.has(base) || base.endsWith('.lock'))
    return { role: 'manifest-lock', evidence: 'path' };
  if (
    segs.includes('.github') ||
    /^tsconfig.*\.json$/.test(base) ||
    /\.config\.(js|mjs|cjs|ts)$/.test(base) ||
    /^biome\.jsonc?$/.test(base) ||
    base.startsWith('.eslintrc') ||
    base.startsWith('.prettierrc') ||
    base.startsWith('jest.config.') ||
    base.startsWith('vitest.config.') ||
    base === 'BUILD' || base === 'BUILD.bazel' || base === '.bazelrc' ||
    base === 'Makefile' || base === 'Dockerfile' || base.startsWith('rust-toolchain')
  )
    return { role: 'tooling-ci', evidence: 'path' };
  if (
    ['.md', '.mdx', '.adoc', '.rst', '.txt'].includes(ext) ||
    segs[0] === 'docs' ||
    /^(README|CHANGELOG|LICENSE|CONTRIBUTING)/i.test(base)
  )
    return { role: 'docs', evidence: 'path' };
  if (
    segs.some((s) => ['test', 'tests', '__tests__', 'spec', 'specs'].includes(s)) ||
    /(_test|_spec|\.test|\.spec)\.[A-Za-z0-9]+$/.test(base) ||
    /^(test|spec)_/.test(base)
  )
    return { role: 'test', evidence: 'path' };
  if (segs.some((s) => ['dist', 'gen', 'generated'].includes(s)))
    return { role: 'generated', evidence: 'path' };
  const content = treeFiles.has(p) ? contentAtBasis(p) : null;
  if (genMarker(content)) return { role: 'generated', evidence: 'content' };
  if (SOURCE_EXTS.has(ext)) return { role: 'source', evidence: 'path' };
  return { role: 'UNKNOWN', evidence: 'path' };
}

// ---- exposure classes (§12), verbatim from META-374 exposure.mjs ----
const stem = (p) => basename(p, extname(p));
function tokens(p) {
  const s = stem(p);
  const out = new Set([s]);
  const d = basename(dirname(p));
  if (d && d !== 'src' && d !== '.') out.add(d);
  return [...out].filter((t) => t.length > 2);
}
function exposure(a, b) {
  const existsA = treeFiles.has(a);
  const existsB = treeFiles.has(b);
  const classes = {};
  const lockish = /(^|\/)(.*\.lock|.*-lock\.json|pnpm-lock\.yaml|yarn\.lock|Cargo\.lock)$/;
  const manifestish = /(^|\/)(package\.json|Cargo\.toml)$/;
  classes['manifest-lock'] =
    (lockish.test(a) && manifestish.test(b)) || (lockish.test(b) && manifestish.test(a));
  classes['stem'] = stem(a) === stem(b) || stem(a).startsWith(stem(b)) || stem(b).startsWith(stem(a));
  classes['same-dir'] = dirname(a) === dirname(b);

  if (!existsA || !existsB) {
    classes['static-edge'] = 'UNKNOWN';
  } else {
    const A = contentAtBasis(a);
    const B = contentAtBasis(b);
    let edge = false;
    try {
      if (A && tokens(b).some((t) => new RegExp(`\\b${t}\\b`).test(A))) edge = true;
      if (!edge && B && tokens(a).some((t) => new RegExp(`\\b${t}\\b`).test(B))) edge = true;
    } catch {
      classes['static-edge'] = 'UNKNOWN';
    }
    if (classes['static-edge'] !== 'UNKNOWN') classes['static-edge'] = edge;
  }

  if (!existsA && !existsB) {
    classes['generated-marker'] = 'UNKNOWN';
  } else {
    const A = existsA ? contentAtBasis(a) : null;
    const B = existsB ? contentAtBasis(b) : null;
    classes['generated-marker'] = genMarker(A) || genMarker(B);
  }
  return classes;
}

// ---- held-out transactions over (basis, pin] (§13) ----
const shas =
  basis === pin
    ? []
    : git('rev-list', '--first-parent', '--reverse', `${basis}..${pin}`).trim().split('\n').filter(Boolean);
const transactions = [];
for (const sha of shas) {
  const subject = git('log', '-1', '--format=%s', sha).trim();
  const parents = git('rev-list', '--parents', '-n', '1', sha).trim().split(' ').slice(1);
  const parent = parents[0];
  const raw = parent
    ? git('diff-tree', '-r', '--name-status', '-M50%', '--no-commit-id', parent, sha).trim()
    : '';
  const files = raw
    ? raw.split('\n').map((l) => {
        const t = l.split('\t');
        return t[t.length - 1];
      })
    : [];
  const s = subject.toLowerCase();
  const isRelease =
    /^(chore\(release\)|release[:(]|chore: release)/.test(s) ||
    /^v?\d+\.\d+\.\d+/.test(s) ||
    (/^chore/.test(s) && /\brelease\b/.test(s));
  const isRevert = /^revert/.test(s);
  const isDep =
    /^(chore|fix|build)\(deps(-dev)?\)/.test(s) ||
    /^(chore|build): (update|bump) /.test(s) ||
    /\b(bump|update)\b.*\b(to v?\d|dependency|dependencies|lockfile)\b/.test(s);
  transactions.push({
    sha,
    subject,
    mergeOnFirstParent: parents.length > 1,
    bulk: files.length > 50,
    release: isRelease,
    revert: isRevert,
    dependency: isDep,
    nFiles: files.length,
    fileSet: new Set(files),
  });
}
const usable = transactions.filter(
  (t) => !t.mergeOnFirstParent && !t.bulk && !t.release && !t.revert && !t.dependency,
);
const nonMerge = transactions.filter((t) => !t.mergeOnFirstParent);

// ---- per-relationship characterization ----
const roleCache = new Map();
const role = (p) => {
  if (!roleCache.has(p)) roleCache.set(p, roleOf(p));
  return roleCache.get(p);
};

const relationships = dump.pairs.map((p) => {
  const [a, b] = p.files;
  const existsA = treeFiles.has(a);
  const existsB = treeFiles.has(b);
  const exp = exposure(a, b);
  const overlapAll = nonMerge.some((t) => t.fileSet.has(a) && t.fileSet.has(b));
  const overlapUsable = usable.some((t) => t.fileSet.has(a) && t.fileSet.has(b));
  const exposureClasses = Object.entries(exp)
    .filter(([, v]) => v === true)
    .map(([k]) => k);
  return {
    rank: p.rank,
    files: p.files,
    support: p.support,
    occurrences: p.occurrences,
    emitted: p.emitted,
    existsA,
    existsB,
    roleA: role(a),
    roleB: role(b),
    mostRecentSupport: p.mostRecentSupport,
    firstSupport: p.firstSupport,
    subwindowPresence: p.subwindowPresence,
    exposure: exp,
    exposureClasses,
    exposureUnknown: Object.values(exp).filter((v) => v === 'UNKNOWN'),
    noPreregisteredExposure: exposureClasses.length === 0,
    heldOut: { overlapAll, overlapUsable },
  };
});

// ---- target files (§14) ----
const targets = repoCfg.targets.map((t) => {
  if (!treeFiles.has(t)) return { target: t, state: 'TARGET_ABSENT_AT_BASIS' };
  const partners = relationships.filter((r) => r.files.includes(t));
  if (partners.length === 0)
    return { target: t, state: 'TARGET_PRESENT_ZERO_QUALIFYING_PARTNERS' };
  return {
    target: t,
    state: `TARGET_PRESENT_${partners.length}_QUALIFYING_PARTNERS`,
    total: partners.length,
    inGlobalTop50: partners.filter((r) => r.emitted).length,
    omitted: partners.filter((r) => !r.emitted).length,
    partners: partners.map((r) => ({
      rank: r.rank,
      other: r.files[0] === t ? r.files[1] : r.files[0],
      support: r.support,
      occurrences: r.occurrences,
      emitted: r.emitted,
      otherExists: r.files[0] === t ? r.existsB : r.existsA,
      otherRole: r.files[0] === t ? r.roleB : r.roleA,
      ageFromBasis: r.mostRecentSupport?.deltaPos ?? null,
      exposureClasses: r.exposureClasses,
      heldOut: r.heldOut,
    })),
  };
});

writeFileSync(
  join(outDir, `${label}.characterization.json`),
  JSON.stringify(
    {
      label,
      repo: repoName,
      basis,
      pin,
      heldOutWindow: {
        transactionsTotal: transactions.length,
        mergeOnFirstParentExcluded: transactions
          .filter((t) => t.mergeOnFirstParent)
          .map((t) => t.sha),
        bulk: transactions.filter((t) => t.bulk).map((t) => ({ sha: t.sha, nFiles: t.nFiles, subject: t.subject })),
        release: transactions.filter((t) => t.release).length,
        revert: transactions.filter((t) => t.revert).length,
        dependency: transactions.filter((t) => t.dependency).length,
        usable: usable.length,
      },
      relationships,
      targets,
    },
    null,
    1,
  ) + '\n',
);
console.log(
  `${label}: relationships=${relationships.length} heldOut=${transactions.length} usable=${usable.length} targets=${targets.map((t) => t.state).join(',')}`,
);
